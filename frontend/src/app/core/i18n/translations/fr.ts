/** Widens every leaf of `typeof fr` from its literal French string to
 * plain `string` — otherwise TypeScript would require `en.ts` to contain
 * the exact same French text at every key, `as const` locking each leaf
 * to its literal value. */
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };

export type TranslationDictionary = Widen<typeof fr>;
